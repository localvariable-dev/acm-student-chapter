-- Apply this once in the Supabase SQL Editor before deploying the API.
-- The API uses the server-only secret key. No browser roles receive table access.

create table public.applications (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  contact_number text not null,
  email text not null,
  roll_no text not null,
  gender text not null check (gender in ('Male', 'Female')),
  year text not null check (year in ('SE', 'TE')),
  domain text not null check (domain in (
    'Event Management', 'PR & Media', 'Marketing',
    'Design & Creative', 'Tech Team', 'Data Team'
  )),
  experience text not null default '',
  status text not null default 'pending'
);

alter table public.applications enable row level security;
revoke all on table public.applications from public, anon, authenticated;
grant usage on schema public to service_role;
grant insert on table public.applications to service_role;
revoke all on sequence public.applications_id_seq from public, anon, authenticated;
grant usage on sequence public.applications_id_seq to service_role;
